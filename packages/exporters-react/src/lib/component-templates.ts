function generateDataTable(name: string): string {
  return joinLines([
    `'use client';`,
    ``,
    `import type { DateRange, Row } from '../types';`,
    `import { isNumericFieldKey, TABLE_NUMERIC_CELL_CLASS } from '../presentation/numeric-fields';`,
    ``,
    `export interface ${name}Props {`,
    `  id?: string;`,
    `  data: Row[];`,
    `  filter?: DateRange;`,
    `  pageSize?: number;`,
    `  sortable?: boolean;`,
    `  filterable?: boolean;`,
    `  selectedRow?: Row;`,
    `  onSelectRow?: (row: Row) => void;`,
    `}`,
    ``,
    `export function ${name}({ id, data, filter, pageSize = 25, sortable = true, filterable = true, selectedRow, onSelectRow }: ${name}Props) {`,
    `  const rows = filterRows(data, filter).slice(0, pageSize);`,
    `  const columns = rows.length > 0 ? Object.keys(rows[0]) : ['id', 'label', 'value'];`,
    ``,
    `  return (`,
    `    <section className="table-card" id={id} data-sortable={sortable} data-filterable={filterable}>`,
    `      <table className="table">`,
    `        <thead>`,
    `          <tr>`,
    `            {columns.map((column) => (`,
    `              <th key={column} className={isNumericFieldKey(column) ? TABLE_NUMERIC_CELL_CLASS : undefined}>`,
    `                {column}`,
    `              </th>`,
    `            ))}`,
    `          </tr>`,
    `        </thead>`,
    `        <tbody>`,
    `          {rows.map((row, index) => (`,
    `            <tr`,
    `              key={String(row.id ?? index)}`,
    `              className={selectedRow?.id === row.id ? 'table-row table-row--selected' : 'table-row'}`,
    `              onClick={() => onSelectRow?.(row)}`,
    `            >`,
    `              {columns.map((column) => (`,
    `                <td key={column} className={isNumericFieldKey(column) ? TABLE_NUMERIC_CELL_CLASS : undefined}>`,
    `                  {String(row[column] ?? '')}`,
    `                </td>`,
    `              ))}`,
    `            </tr>`,
    `          ))}`,
    `        </tbody>`,
    `      </table>`,
    `    </section>`,
    `  );`,
    `}`,
    ``,
    `function filterRows(data: Row[], filter?: DateRange): Row[] {`,
    `  if (!filter) {`,
    `    return data;`,
    `  }`,
    `  return data.filter((row) => {`,
    `    const value = String(row.date ?? row.createdAt ?? '');`,
    `    if (!value) {`,
    `      return true;`,
    `    }`,
    `    return value >= filter.start && value <= filter.end;`,
    `  });`,
    `}`,
    ``,
  ]);
}

