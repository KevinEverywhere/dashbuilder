import { joinLines } from './utils';

export function generateEquirectFilterHelperFile(): string {
  return joinLines([
    `export interface EquirectFlatCropOptions {`,
    `  cropX: number;`,
    `  cropY: number;`,
    `  cropWidth: number;`,
    `  cropHeight: number;`,
    `  outputWidth: number;`,
    `  outputHeight: number;`,
    `}`,
    ``,
    `export function buildEquirectFlatCropFilter(options: EquirectFlatCropOptions): string {`,
    `  const cropX = Math.max(0, Math.round(options.cropX));`,
    `  const cropY = Math.max(0, Math.round(options.cropY));`,
    `  const cropWidth = Math.max(2, Math.round(options.cropWidth));`,
    `  const cropHeight = Math.max(2, Math.round(options.cropHeight));`,
    `  const outputWidth = Math.max(2, Math.round(options.outputWidth));`,
    `  const outputHeight = Math.max(2, Math.round(options.outputHeight));`,
    `  return \`crop=\${cropWidth}:\${cropHeight}:\${cropX}:\${cropY},scale=\${outputWidth}:\${outputHeight}\`;`,
    `}`,
    ``,
    `export function buildEquirectRectilinearFilter(options: {`,
    `  yaw: number;`,
    `  pitch: number;`,
    `  roll?: number;`,
    `  horizontalFov: number;`,
    `  outputWidth: number;`,
    `  outputHeight: number;`,
    `}): string {`,
    `  const yaw = Number(options.yaw) || 0;`,
    `  const pitch = Number(options.pitch) || 0;`,
    `  const roll = Number(options.roll ?? 0) || 0;`,
    `  const horizontalFov = Math.max(1, Number(options.horizontalFov) || 90);`,
    `  const outputWidth = Math.max(2, Math.round(options.outputWidth));`,
    `  const outputHeight = Math.max(2, Math.round(options.outputHeight));`,
    `  return [`,
    `    \`v360=input=equirect:output=rectilinear:yaw=\${yaw}:pitch=\${pitch}:roll=\${roll}:d_fov=\${horizontalFov}\`,`,
    `    \`scale=\${outputWidth}:\${outputHeight}\`,`,
    `  ].join(',');`,
    `}`,
    ``,
    `export function buildEquirectExtractFilter(`,
    `  mode: 'flat-crop' | 'rectilinear',`,
    `  options: EquirectFlatCropOptions & {`,
    `    yaw?: number;`,
    `    pitch?: number;`,
    `    roll?: number;`,
    `    horizontalFov?: number;`,
    `  },`,
    `): string {`,
    `  if (mode === 'rectilinear') {`,
    `    return buildEquirectRectilinearFilter({`,
    `      yaw: options.yaw ?? 0,`,
    `      pitch: options.pitch ?? 0,`,
    `      roll: options.roll ?? 0,`,
    `      horizontalFov: options.horizontalFov ?? 90,`,
    `      outputWidth: options.outputWidth,`,
    `      outputHeight: options.outputHeight,`,
    `    });`,
    `  }`,
    `  return buildEquirectFlatCropFilter(options);`,
    `}`,
    ``,
  ]);
}

export function generateVideoSource(name: string): string {
  return joinLines([
    `<script setup lang="ts">`,
    `import { ref } from 'vue';`,
    `import type { Row } from '../types';`,
    ``,
    `const props = withDefaults(`,
    `  defineProps<{`,
    `    id?: string;`,
    `    label?: string;`,
    `    accept?: string;`,
    `    url?: string;`,
    `    sourceWidth?: number;`,
    `    sourceHeight?: number;`,
    `    captureBlob?: Blob;`,
    `  }>(),`,
    `  { label: 'Video source', accept: 'video/*', url: '', sourceWidth: 4096, sourceHeight: 2048 },`,
    `);`,
    ``,
    `const emit = defineEmits<{`,
    `  videoFile: [file: File];`,
    `  metadata: [row: Row];`,
    `}>();`,
    ``,
    `const fileName = ref('');`,
    ``,
    `function emitFile(file: File) {`,
    `  fileName.value = file.name;`,
    `  emit('videoFile', file);`,
    `  emit('metadata', {`,
    `    name: file.name,`,
    `    sourceWidth: props.sourceWidth,`,
    `    sourceHeight: props.sourceHeight,`,
    `    size: file.size,`,
    `  });`,
    `}`,
    `</script>`,
    ``,
    `<template>`,
    `  <section class="media-source" :id="id">`,
    `    <header class="media-source__header">`,
    `      <h3>{{ label }}</h3>`,
    `      <span>{{ sourceWidth }}×{{ sourceHeight }}</span>`,
    `    </header>`,
    `    <label class="media-source__upload">`,
    `      <input type="file" :accept="accept" @change="(event) => {`,
    `        const file = (event.target as HTMLInputElement).files?.[0];`,
    `        if (file) emitFile(file);`,
    `      }" />`,
    `      <span>{{ fileName || 'Choose video file' }}</span>`,
    `    </label>`,
    `    <p v-if="url" class="media-source__url">URL: {{ url }}</p>`,
    `    <p v-if="captureBlob" class="media-source__capture">Live capture attached</p>`,
    `  </section>`,
    `</template>`,
    ``,
  ]);
}

