export function generateComponentFile(component: IRComponent, className: string): string {
  if (!SUPPORTED_TYPES.has(component.type)) {
    throw new AngularExportError(`Unsupported Angular export component type: ${component.type}`);
  }

  switch (component.type) {
    case 'visual.input.text':
      return generateTextInput(className);
    case 'visual.input.select':
      return generateSelectInput(className);
    case 'visual.input.number':
      return generateNumberInput(className);
    case 'visual.input.checkbox':
      return generateCheckboxInput(className);
    case 'visual.input.textarea':
      return generateTextareaInput(className);
    case 'visual.input.date-range':
      return generateDateRangeFilter(className);
    case 'domain.time-preset':
      return generateTimePreset(className);
    case 'visual.table':
      return generateDataTable(className);
    case 'visual.detail':
      return generateDetailPanel(className);
    case 'visual.skeleton':
      return generateSkeleton(className);
    case 'visual.kpi':
      return generateKpiCard(className);
    case 'visual.chart.line':
      return generateLineChart(className);
    case 'visual.chart.bar':
      return generateBarChart(className);
    case 'visual.chart.pie':
      return generatePieChart(className);
    case 'visual.display.3d-bar-chart':
      return generateThreeBarChart(className);
    case 'visual.display.3d-scatter':
      return generateThreeScatterPlot(className);
    case 'visual.display.3d-scene':
      return generateThreeScenePointCloud(className);
    case 'visual.display.3d-gltf-model':
      return generateThreeGltfModel(className);
    case 'visual.display.3d-geo-globe':
      return generateThreeGeoGlobe(className);
    case 'visual.svg.inline':
      return generateSvgInline(className);
    case 'visual.svg.icon':
      return generateSvgIcon(className);
    case 'infra.wasm.asset':
      return generateWasmAsset(className);
    case 'visual.wasm.worker-host':
      return generateWasmWorkerHost(className);
    case 'visual.wasm.module':
      return generateWasmModule(className);
    case 'visual.wasm.media':
      return component.properties?.['operation'] === 'equirect-extract'
        ? generateWasmMediaEquirect(className)
        : generateWasmMedia(className);
    case 'visual.media.video-source':
      return generateVideoSource(className);
    case 'visual.media.equirect-viewport':
      return generateEquirectViewport(className);
    case 'visual.media.live-capture':
      return generateLiveCapture(className);
    case 'domain.role-gate':
      return generateRoleGate(className);
    case 'domain.person-invite':
      return generatePersonInvite(className);
    case 'domain.role-assign':
      return generateRoleAssign(className);
    case 'logic.timer':
      return generateTimer(className);
    case 'visual.news.language-select':
    case 'visual.news.region-select':
    case 'visual.news.type-select':
      return generateSelectInput(className);
    case 'visual.news.search-box':
      return generateTextInput(className);
    case 'visual.news.results-table':
      return generateDataTable(className);
    case 'visual.news.article-detail':
      return generateDetailPanel(className);
    default:
      throw new AngularExportError(`Missing Angular template for ${component.type}`);
  }
}

function generateTextInput(className: string): string {
  const selector = selectorFromClass(className);
  return joinLines([
    `import { Component, input, output } from '@angular/core';`,
    ``,
    `@Component({`,
    `  selector: '${selector}',`,
    `  standalone: true,`,
    `  template: \``,
    `    <label class="field" [attr.for]="id()">`,
    `      <input`,
    `        class="input"`,
    `        type="text"`,
    `        [id]="id()"`,
    `        [placeholder]="placeholder()"`,
    `        [required]="required()"`,
    `        [value]="value() ?? ''"`,
    `        (input)="valueChange.emit($any($event.target).value)"`,
    `      />`,
    `    </label>`,
    `  \`,`,
    `})`,
    `export class ${className} {`,
    `  id = input<string>();`,
    `  placeholder = input('');`,
    `  required = input(false);`,
    `  value = input<string>();`,
    `  valueChange = output<string>();`,
    `}`,
    ``,
  ]);
}

