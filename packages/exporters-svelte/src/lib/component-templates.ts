function generateDataTable(): string {
  return joinLines([
    `<script lang="ts">`,
    `  import type { DateRange, Row } from '../types';`,
    `  import { isNumericFieldKey } from '../presentation/numeric-fields';`,
    `  let {`,
    `    id,`,
    `    data = [] as Row[],`,
    `    filter,`,
    `    pageSize = 25,`,
    `    sortable = true,`,
    `    filterable = true,`,
    `    selectedRow,`,
    `    onSelectRow,`,
    `  }: {`,
    `    id?: string;`,
    `    data?: Row[];`,
    `    filter?: DateRange;`,
    `    pageSize?: number;`,
    `    sortable?: boolean;`,
    `    filterable?: boolean;`,
    `    selectedRow?: Row;`,
    `    onSelectRow?: (row: Row) => void;`,
    `  } = $props();`,
    ``,
    `  const rows = $derived(filterRows(data, filter).slice(0, pageSize));`,
    `  const columns = $derived.by(() => {`,
    `    const first = rows[0];`,
    `    return first ? Object.keys(first) : ['id', 'label', 'value'];`,
    `  });`,
    ``,
    `  function filterRows(source: Row[], value?: DateRange): Row[] {`,
    `    if (!value) return source;`,
    `    return source.filter((row) => {`,
    `      const dateValue = String(row.date ?? row.createdAt ?? '');`,
    `      if (!dateValue) return true;`,
    `      return dateValue >= value.start && dateValue <= value.end;`,
    `    });`,
    `  }`,
    `</script>`,
    ``,
    `<section class="table-card" {id} data-sortable={sortable} data-filterable={filterable}>`,
    `  <table class="table">`,
    `    <thead>`,
    `      <tr>`,
    `        {#each columns as column (column)}`,
    `          <th class:table-cell--numeric={isNumericFieldKey(column)}>{column}</th>`,
    `        {/each}`,
    `      </tr>`,
    `    </thead>`,
    `    <tbody>`,
    `      {#each rows as row, index (String(row.id ?? index))}`,
    `        <tr`,
    `          class={selectedRow?.id === row.id ? 'table-row table-row--selected' : 'table-row'}`,
    `          onclick={() => onSelectRow?.(row)}`,
    `        >`,
    `          {#each columns as column (column)}`,
    `            <td class:table-cell--numeric={isNumericFieldKey(column)}>{row[column] ?? ''}</td>`,
    `          {/each}`,
    `        </tr>`,
    `      {/each}`,
    `    </tbody>`,
    `  </table>`,
    `</section>`,
    ``,
  ]);
}

function generateDetailPanel(): string {
  return joinLines([
    `<script lang="ts">`,
    `  import type { Row } from '../types';`,
    `  import { isNumericFieldKey } from '../presentation/numeric-fields';`,
    `  let {`,
    `    id,`,
    `    title = 'Details',`,
    `    emptyMessage = 'Select a row to view details',`,
    `    row,`,
    `  }: {`,
    `    id?: string;`,
    `    title?: string;`,
    `    emptyMessage?: string;`,
    `    row?: Row;`,
    `  } = $props();`,
    ``,
    `  const fields = $derived.by(() => {`,
    `    if (!row) return [] as Array<{ key: string; value: string }>;`,
    `    return Object.entries(row).map(([key, value]) => ({`,
    `      key,`,
    `      value: String(value ?? ''),`,
    `    }));`,
    `  });`,
    `</script>`,
    ``,
    `<section class="detail-panel" {id}>`,
    `  <h3>{title}</h3>`,
    `  {#if fields.length === 0}`,
    `    <p class="detail-panel__empty">{emptyMessage}</p>`,
    `  {:else}`,
    `    <dl class="detail-panel__fields">`,
    `      {#each fields as field (field.key)}`,
    `        <div class="detail-panel__field">`,
    `          <dt>{field.key}</dt>`,
    `          <dd class:detail-panel__value--numeric={isNumericFieldKey(field.key)}>{field.value}</dd>`,
    `        </div>`,
    `      {/each}`,
    `    </dl>`,
    `  {/if}`,
    `</section>`,
    ``,
  ]);
}

