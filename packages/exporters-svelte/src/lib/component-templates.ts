function generateLineChart(): string {
  return joinLines([
    `<script lang="ts">`,
    `  import type { DateRange, Row } from '../types';`,
    `  let {`,
    `    id,`,
    `    title = 'Chart',`,
    `    xField = 'date',`,
    `    yField = 'value',`,
    `    data = [] as Row[],`,
    `    range,`,
    `  }: {`,
    `    id?: string;`,
    `    title?: string;`,
    `    xField?: string;`,
    `    yField?: string;`,
    `    data?: Row[];`,
    `    range?: DateRange;`,
    `  } = $props();`,
    ``,
    `  const filtered = $derived(filterByRange(data, range));`,
    `  const points = $derived.by(() => {`,
    `    const max = Math.max(...filtered.map((row) => Number(row[yField] ?? 0)), 1);`,
    `    return filtered`,
    `      .map((row, index) => {`,
    `        const x = (index / Math.max(filtered.length - 1, 1)) * 300 + 10;`,
    `        const y = 110 - (Number(row[yField] ?? 0) / max) * 90;`,
    `        return \`\${x},\${y}\`;`,
    `      })`,
    `      .join(' ');`,
    `  });`,
    ``,
    `  function filterByRange(source: Row[], value?: DateRange): Row[] {`,
    `    if (!value) return source;`,
    `    return source.filter((row) => {`,
    `      const dateValue = String(row.date ?? row.createdAt ?? '');`,
    `      if (!dateValue) return true;`,
    `      return dateValue >= value.start && dateValue <= value.end;`,
    `    });`,
    `  }`,
    `</script>`,
    ``,
    `<section class="chart-card" {id}>`,
    `  <h3>{title}</h3>`,
    `  <svg class="line-chart" viewBox="0 0 320 120" role="img" aria-label={title}>`,
    `    <polyline fill="none" stroke="currentColor" stroke-width="2" points={points} />`,
    `  </svg>`,
    `  <p class="chart-meta">{filtered.length} points · x={xField} · y={yField}</p>`,
    `</section>`,
    ``,
  ]);
}

