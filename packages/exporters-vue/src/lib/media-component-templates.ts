export function generateLiveCapture(name: string): string {
  return joinLines([
    `<script setup lang="ts">`,
    `import { onUnmounted, ref } from 'vue';`,
    ``,
    `const props = withDefaults(`,
    `  defineProps<{`,
    `    id?: string;`,
    `    label?: string;`,
    `    includeInExport?: boolean;`,
    `    facingMode?: 'user' | 'environment';`,
    `    audio?: boolean;`,
    `  }>(),`,
    `  { label: 'Live capture', includeInExport: false, facingMode: 'environment', audio: true },`,
    `);`,
    ``,
    `const emit = defineEmits<{`,
    `  captureBlob: [blob: Blob];`,
    `  previewUrl: [url: string];`,
    `}>();`,
    ``,
    `const videoRef = ref<HTMLVideoElement | null>(null);`,
    `const active = ref(false);`,
    `let stream: MediaStream | null = null;`,
    ``,
    `onUnmounted(() => {`,
    `  stream?.getTracks().forEach((track) => track.stop());`,
    `});`,
    ``,
    `async function startCapture() {`,
    `  stream = await navigator.mediaDevices.getUserMedia({`,
    `    video: { facingMode: props.facingMode },`,
    `    audio: props.audio,`,
    `  });`,
    `  if (videoRef.value) {`,
    `    videoRef.value.srcObject = stream;`,
    `    await videoRef.value.play();`,
    `  }`,
    `  active.value = true;`,
    `  emit('previewUrl', 'live');`,
    `}`,
    `</script>`,
    ``,
    `<template>`,
    `  <section v-if="!includeInExport" class="media-capture media-capture--authoring" :id="id">`,
    `    <p>{{ label }} (authoring only — enable includeInExport for runtime capture)</p>`,
    `  </section>`,
    `  <section v-else class="media-capture" :id="id">`,
    `    <header><h3>{{ label }}</h3></header>`,
    `    <video ref="videoRef" class="media-capture__video" muted playsinline />`,
    `    <button type="button" @click="startCapture">`,
    `      {{ active ? 'Camera active' : 'Start camera' }}`,
    `    </button>`,
    `  </section>`,
    `</template>`,
    ``,
  ]);
}

export function generateWasmMediaEquirect(name: string): string {
  return joinLines([
    `<script setup lang="ts">`,
    `/** Requires: npm install @ffmpeg/ffmpeg @ffmpeg/util */`,
    `import { computed, ref } from 'vue';`,
    `import { FFmpeg } from '@ffmpeg/ffmpeg';`,
    `import { fetchFile, toBlobURL } from '@ffmpeg/util';`,
    `import type { Row } from '../types';`,
    `import { buildEquirectExtractFilter } from '../media/equirect-filter';`,
    ``,
    `const props = withDefaults(`,
    `  defineProps<{`,
    `    id?: string;`,
    `    label?: string;`,
    `    operation?: string;`,
    `    extractionMode?: 'flat-crop' | 'rectilinear';`,
    `    outputFormat?: string;`,
    `    cropX?: number;`,
    `    cropY?: number;`,
    `    cropWidth?: number;`,
    `    cropHeight?: number;`,
    `    outputWidth?: number;`,
    `    outputHeight?: number;`,
    `    yaw?: number;`,
    `    pitch?: number;`,
    `    horizontalFov?: number;`,
    `    showProgress?: boolean;`,
    `    inputFile?: File | Blob;`,
    `    cropRegion?: Row;`,
    `  }>(),`,
    `  {`,
    `    label: 'Media transcode',`,
    `    operation: 'transcode',`,
    `    extractionMode: 'flat-crop',`,
    `    outputFormat: 'mp4',`,
    `    cropX: 1508,`,
    `    cropY: 664,`,
    `    cropWidth: 1080,`,
    `    cropHeight: 720,`,
    `    outputWidth: 720,`,
    `    outputHeight: 480,`,
    `    yaw: 0,`,
    `    pitch: 0,`,
    `    horizontalFov: 90,`,
    `    showProgress: true,`,
    `  },`,
    `);`,
    ``,
    `const emit = defineEmits<{`,
    `  outputBlob: [blob: Blob];`,
    `  progress: [value: number];`,
    `  metadata: [rows: Row[]];`,
    `}>();`,
    ``,
    `const ffmpeg = ref<FFmpeg | null>(null);`,
    `const progress = ref(0);`,
    `const busy = ref(false);`,
    `const error = ref<string | null>(null);`,
    ``,
    `function resolveCrop() {`,
    `  return {`,
    `    cropX: Number(props.cropRegion?.cropX ?? props.cropX),`,
    `    cropY: Number(props.cropRegion?.cropY ?? props.cropY),`,
    `    cropWidth: Number(props.cropRegion?.cropWidth ?? props.cropWidth),`,
    `    cropHeight: Number(props.cropRegion?.cropHeight ?? props.cropHeight),`,
    `    outputWidth: Number(props.cropRegion?.outputWidth ?? props.outputWidth),`,
    `    outputHeight: Number(props.cropRegion?.outputHeight ?? props.outputHeight),`,
    `  };`,
    `}`,
    ``,
    `async function ensureFfmpeg() {`,
    `  if (ffmpeg.value) return ffmpeg.value;`,
    `  const instance = new FFmpeg();`,
    `  instance.on('progress', ({ progress: ratio }) => {`,
    `    const next = Math.round(ratio * 100);`,
    `    progress.value = next;`,
    `    emit('progress', next);`,
    `  });`,
    `  const baseURL = 'https://unpkg.com/@ffmpeg/core@0.12.6/dist/umd';`,
    `  await instance.load({`,
    `    coreURL: await toBlobURL(\`\${baseURL}/ffmpeg-core.js\`, 'text/javascript'),`,
    `    wasmURL: await toBlobURL(\`\${baseURL}/ffmpeg-core.wasm\`, 'application/wasm'),`,
    `  });`,
    `  ffmpeg.value = instance;`,
    `  return instance;`,
    `}`,
    ``,
    `async function runEquirectExtract() {`,
    `  if (!props.inputFile) {`,
    `    error.value = 'Attach a video file before extracting.';`,
    `    return;`,
    `  }`,
    `  busy.value = true;`,
    `  error.value = null;`,
    `  try {`,
    `    const instance = await ensureFfmpeg();`,
    `    const inputName = 'input.mp4';`,
    `    const outputName = \`output.\${props.outputFormat}\`;`,
    `    await instance.writeFile(inputName, await fetchFile(props.inputFile));`,
    `    const crop = resolveCrop();`,
    `    const filter = buildEquirectExtractFilter(props.extractionMode, {`,
    `      ...crop,`,
    `      yaw: props.yaw,`,
    `      pitch: props.pitch,`,
    `      horizontalFov: props.horizontalFov,`,
    `    });`,
    `    await instance.exec(['-i', inputName, '-vf', filter, '-c:a', 'copy', outputName]);`,
    `    const data = await instance.readFile(outputName);`,
    `    const blob = new Blob([data], { type: \`video/\${props.outputFormat}\` });`,
    `    emit('outputBlob', blob);`,
    `    emit('metadata', [{`,
    `      filter,`,
    `      outputWidth: crop.outputWidth,`,
    `      outputHeight: crop.outputHeight,`,
    `      format: props.outputFormat,`,
    `    }]);`,
    `  } catch (nextError) {`,
    `    error.value = nextError instanceof Error ? nextError.message : 'Extract failed';`,
    `  } finally {`,
    `    busy.value = false;`,
    `  }`,
    `}`,
    ``,
    `const filterPreview = computed(() =>`,
    `  props.operation === 'equirect-extract'`,
    `    ? buildEquirectExtractFilter(props.extractionMode, {`,
    `        ...resolveCrop(),`,
    `        yaw: props.yaw,`,
    `        pitch: props.pitch,`,
    `        horizontalFov: props.horizontalFov,`,
    `      })`,
    `    : '',`,
    `);`,
    `</script>`,
    ``,
    `<template>`,
    `  <section class="wasm-media" :id="id">`,
    `    <header class="wasm-media__header">`,
    `      <h3>{{ label }}</h3>`,
    `      <span>{{ operation }} → {{ outputFormat }}</span>`,
    `    </header>`,
    `    <code v-if="filterPreview" class="wasm-media__filter">{{ filterPreview }}</code>`,
    `    <div v-if="showProgress" class="wasm-media__progress" role="progressbar" :aria-valuenow="progress">`,
    `      <span :style="{ width: \`\${progress}%\` }" />`,
    `    </div>`,
    `    <button`,
    `      v-if="operation === 'equirect-extract'"`,
    `      type="button"`,
    `      :disabled="busy || !inputFile"`,
    `      @click="runEquirectExtract"`,
    `    >`,
    `      {{ busy ? 'Extracting…' : 'Extract subsection' }}`,
    `    </button>`,
    `    <p v-else class="wasm-media__hint">Wire input file and choose equirect-extract operation.</p>`,
    `    <p v-if="error" class="wasm-media__error">{{ error }}</p>`,
    `  </section>`,
    `</template>`,
    ``,
  ]);
}
