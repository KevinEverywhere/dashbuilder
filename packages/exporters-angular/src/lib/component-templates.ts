function generateDataTable(className: string): string {
  const selector = selectorFromClass(className);
  return joinLines([
    `import { Component, computed, input } from '@angular/core';`,
    `import type { DateRange, Row } from '../types';`,
    `import { isNumericFieldKey } from '../presentation/numeric-fields';`,
    ``,
    `@Component({`,
    `  selector: '${selector}',`,
    `  standalone: true,`,
    `  template: \``,
    `    <section class="table-card" [id]="id()" [attr.data-sortable]="sortable()" [attr.data-filterable]="filterable()">`,
    `      <table class="table">`,
    `        <thead>`,
    `          <tr>`,
    `            @for (column of columns(); track column) {`,
    `              <th [class.table-cell--numeric]="isNumericFieldKey(column)">{{ column }}</th>`,
    `            }`,
    `          </tr>`,
    `        </thead>`,
    `        <tbody>`,
    `          @for (row of rows(); track row.id ?? $index) {`,
    `            <tr`,
    `              class="table-row"`,
    `              [class.table-row--selected]="selectedRow()?.id === row.id"`,
    `              (click)="handleRowSelect(row)"`,
    `            >`,
    `              @for (column of columns(); track column) {`,
    `                <td [class.table-cell--numeric]="isNumericFieldKey(column)">{{ row[column] ?? '' }}</td>`,
    `              }`,
    `            </tr>`,
    `          }`,
    `        </tbody>`,
    `      </table>`,
    `    </section>`,
    `  \`,`,
    `})`,
    `export class ${className} {`,
    `  id = input<string>();`,
    `  data = input<Row[]>([]);`,
    `  filter = input<DateRange>();`,
    `  pageSize = input(25);`,
    `  sortable = input(true);`,
    `  filterable = input(true);`,
    `  selectedRow = input<Row>();`,
    `  onSelectRow = input<(row: Row) => void>();`,
    ``,
    `  rows = computed(() => filterRows(this.data(), this.filter()).slice(0, this.pageSize()));`,
    `  columns = computed(() => {`,
    `    const first = this.rows()[0];`,
    `    return first ? Object.keys(first) : ['id', 'label', 'value'];`,
    `  });`,
    ``,
    `  protected handleRowSelect(row: Row): void {`,
    `    this.onSelectRow()?.(row);`,
    `  }`,
    ``,
    `  protected readonly isNumericFieldKey = isNumericFieldKey;`,
    `}`,
    ``,
    `function filterRows(data: Row[], filter?: DateRange): Row[] {`,
    `  if (!filter) {`,
    `    return data;`,
    `  }`,
    `  return data.filter((row) => {`,
    `    const value = String(row['date'] ?? row['createdAt'] ?? '');`,
    `    if (!value) {`,
    `      return true;`,
    `    }`,
    `    return value >= filter.start && value <= filter.end;`,
    `  });`,
    `}`,
    ``,
  ]);
}

