function generateDateRangeFilter(className: string): string {
  const selector = selectorFromClass(className);
  return joinLines([
    `import { Component, input, output } from '@angular/core';`,
    `import type { DateRange } from '../types';`,
    ``,
    `@Component({`,
    `  selector: '${selector}',`,
    `  standalone: true,`,
    `  template: \``,
    `    <div class="date-range" [id]="id()">`,
    `      <label class="field">`,
    `        <span>Start</span>`,
    `        <input`,
    `          class="input"`,
    `          type="date"`,
    `          [value]="current().start"`,
    `          (input)="onStartChange($any($event.target).value)"`,
    `        />`,
    `      </label>`,
    `      <label class="field">`,
    `        <span>End</span>`,
    `        <input`,
    `          class="input"`,
    `          type="date"`,
    `          [value]="current().end"`,
    `          (input)="onEndChange($any($event.target).value)"`,
    `        />`,
    `      </label>`,
    `    </div>`,
    `  \`,`,
    `})`,
    `export class ${className} {`,
    `  id = input<string>();`,
    `  preset = input('last-7-days');`,
    `  value = input<DateRange>();`,
    `  valueChange = output<DateRange>();`,
    ``,
    `  current(): DateRange {`,
    `    return this.value() ?? defaultRangeForPreset(this.preset());`,
    `  }`,
    ``,
    `  onStartChange(start: string): void {`,
    `    this.valueChange.emit({ ...this.current(), start });`,
    `  }`,
    ``,
    `  onEndChange(end: string): void {`,
    `    this.valueChange.emit({ ...this.current(), end });`,
    `  }`,
    `}`,
    ``,
    `function defaultRangeForPreset(preset: string): DateRange {`,
    `  const end = new Date();`,
    `  const start = new Date(end);`,
    `  if (preset === 'last-30-days') {`,
    `    start.setDate(end.getDate() - 30);`,
    `  } else if (preset === 'qtd') {`,
    `    start.setMonth(Math.floor(end.getMonth() / 3) * 3, 1);`,
    `  } else {`,
    `    start.setDate(end.getDate() - 7);`,
    `  }`,
    `  return { start: formatDate(start), end: formatDate(end) };`,
    `}`,
    ``,
    `function formatDate(date: Date): string {`,
    `  return date.toISOString().slice(0, 10);`,
    `}`,
    ``,
  ]);
}

